"""End-to-end check of the Elastic pieces; writes the transcript to data/elastic_verification.md.

    uv run python elastic_verify.py

1. index counts + embedding model per semantic field
2. hybrid search (BM25 + semantic, RRF, rerank) for "outdoor seating" in astoria
3. every Agent Builder tool via POST /api/agent_builder/tools/_execute
4. run the corridor-brief workflow, poll the execution, confirm a doc landed in `briefs`
5. ask streetshift-analyst one question via POST /api/agent_builder/converse
"""

import json
import sys
import time
from datetime import datetime, timezone

from elastic_common import AGENT_ID, BRIEFS, BUSINESSES, REVIEWS, ROOT, es, kibana
from elastic_search import hybrid_search

OUT = ROOT / "data" / "elastic_verification.md"
QUESTION = ("Which businesses on Ditmars Blvd (corridor ditmars) look most car-dependent, and how did monthly "
            "review volume on ditmars compare with ditmars_control? Cite businesses and review dates.")


def j(x, n=2500):
    s = json.dumps(x, ensure_ascii=False, indent=1, default=str)
    return s if len(s) <= n else s[:n] + "\n... (truncated)"


def main():
    c = es()
    lines = [f"# Elastic verification ({datetime.now(timezone.utc).isoformat(timespec='seconds')})", "",
             "Generated by `data/elastic_verify.py`. Raw outputs, truncated where long.", ""]

    lines += ["## 1. Indexes", ""]
    for idx, field in ((BUSINESSES, "profile"), (REVIEWS, "content"), (BRIEFS, None)):
        cnt = c.count(index=idx)["count"]
        model = None
        if field:
            model = c.indices.get_mapping(index=idx)[idx]["mappings"]["properties"][field].get("inference_id")
        lines.append(f"- `{idx}`: {cnt} docs" + (f", `{field}` semantic_text via `{model}`" if model else ""))
    aggs = c.search(index=REVIEWS, size=0, aggs={"a": {"terms": {"field": "area"}}})["aggregations"]["a"]["buckets"]
    lines.append(f"- reviews per area: {', '.join(f'{b['key']}={b['doc_count']}' for b in aggs)}")
    lines.append("")

    lines += ["## 2. Hybrid search: \"outdoor seating\" (area astoria)", ""]
    hits, mode = hybrid_search("outdoor seating", REVIEWS, 5, area="astoria", client=c)
    lines.append(f"mode: `{mode}`")
    lines.append("")
    for h in hits:
        lines.append(f"- {h['_score']:.3f} **{h['business_name']}** ({h['category']}, {h.get('corridor_id')}, "
                     f"{(h.get('published_at') or '')[:10]}): \"{h['text'][:180].replace(chr(10), ' ')}\"")
    lines.append("")

    lines += ["## 2b. carDependence (data/elastic_car_dependence.py)", "",
              "Per-area mean of `car_dependence` in the `businesses` index:", ""]
    ag = c.search(index=BUSINESSES, size=0, aggs={"a": {"terms": {"field": "area"},
                                                     "aggs": {"m": {"avg": {"field": "car_dependence"}},
                                                              "k": {"sum": {"field": "car_mentions"}}}}})
    for b in ag["aggregations"]["a"]["buckets"]:
        lines.append(f"- {b['key']}: mean {b['m']['value']:.3f} over {b['doc_count']} businesses, "
                     f"{int(b['k']['value'])} car-mention reviews")
    lines += ["", "Calibration history: v1 used the BM25 term `park`, which matched place names (Park Slope mean "
              "0.457 vs 0.14-0.20 elsewhere: \"Prospect Park\", \"Bryant Park\"). `park` and `garage` were dropped, "
              "French reviews skipped (\"car\" = because), `foot traffic`/`car dealership` excluded. Jina v5-small "
              "semantic gate was 0.575; on multilingual-e5-small every BM25 hit scores 0.87-0.93, so the gate is 0.88 "
              "and precision comes from the vocabulary.", "", "Sample car-mention reviews (BM25-gated semantic query):", ""]
    from elastic_car_dependence import car_query, TAU
    for area in ("park_slope", "chinatown", "hayes_valley"):
        hs = c.search(index=REVIEWS, query=car_query([{"term": {"area": area}}]), size=2,
                      source=["business_name", "text", "published_at"])["hits"]["hits"]
        for h in hs:
            lines.append(f"- [{area}] {h['_score']:.3f} {'>=' if h['_score'] >= TAU else '<'} tau: **{h['_source']['business_name']}** "
                         f"({h['_source']['published_at'][:10]}): \"{h['_source']['text'][:200].replace(chr(10), ' ')}\"")
    lines.append("")

    lines += ["## 3. Agent Builder tools (`/api/agent_builder/tools/_execute`)", ""]
    calls = [("streetshift_search", {"nlQuery": "reviews saying parking is hard on Ditmars"}),
             ("review_volume_by_month", {"target": "ditmars"}),
             ("car_dependence_by_corridor", {"corridor": "ditmars"}),
             ("streetshift_briefs", {"nlQuery": "latest briefing for corridor ditmars"})]
    for tid, params in calls:
        r = kibana("POST", "/api/agent_builder/tools/_execute", json={"tool_id": tid, "tool_params": params})
        body = r.json() if r.headers.get("content-type", "").startswith("application/json") else r.text
        lines += [f"### `{tid}` {params} -> HTTP {r.status_code}", "", "```json", j(body, 2000), "```", ""]
        print(f"tool {tid}: {r.status_code}")

    lines += ["## 4. Workflow `corridor-brief`", ""]
    before = c.count(index=BRIEFS)["count"]
    r = kibana("POST", "/api/workflows/workflow/corridor-brief/run", json={"inputs": {"corridor": "ditmars"}})
    lines.append(f"run -> HTTP {r.status_code} `{r.text[:300]}`")
    print(f"workflow run: {r.status_code} {r.text[:200]}")
    exec_id = r.json().get("workflowExecutionId") if r.ok else None
    status = None
    for _ in range(60):
        if not exec_id:
            break
        e = kibana("GET", f"/api/workflows/executions/{exec_id}")
        status = e.json().get("status") if e.ok else f"HTTP {e.status_code}"
        if status in ("completed", "failed", "cancelled", "timed_out", "skipped"):
            break
        time.sleep(5)
    lines.append(f"execution `{exec_id}` final status: `{status}`")
    if exec_id:
        steps = kibana("GET", f"/api/workflows/executions/{exec_id}/steps")
        if steps.ok:
            sl = steps.json()
            sl = sl.get("results", sl) if isinstance(sl, dict) else sl
            lines.append("steps: " + ", ".join(f"{s.get('stepId') or s.get('step_id') or s.get('name')}={s.get('status')}"
                                               for s in (sl if isinstance(sl, list) else [])))
    c.indices.refresh(index=BRIEFS)
    after = c.count(index=BRIEFS)["count"]
    lines.append(f"`briefs` docs before {before}, after {after}")
    latest = c.search(index=BRIEFS, size=1, sort=[{"@timestamp": "desc"}])["hits"]["hits"]
    if latest:
        b = latest[0]["_source"]
        lines += ["", f"Latest brief (corridor `{b.get('corridor_id')}`, {b.get('@timestamp')}):", "", "> " +
                  (b.get("brief") or "").replace("\n", "\n> ")]
    lines.append("")
    print(f"workflow status {status}, briefs {before}->{after}")

    lines += ["## 5. Converse with `streetshift-analyst`", "", f"**Q:** {QUESTION}", ""]
    r = kibana("POST", "/api/agent_builder/converse", json={"input": QUESTION, "agent_id": AGENT_ID}, timeout=600)
    data = r.json() if r.ok else {"error": r.text[:500]}
    tools = [{"tool": s.get("tool_id"), "params": s.get("params")} for s in data.get("steps", [])
             if s.get("type") == "tool_call"]
    lines += [f"HTTP {r.status_code}; tool calls: `{json.dumps(tools, ensure_ascii=False)}`", "",
              "**A:**", "", (data.get("response") or {}).get("message", j(data, 1500)), ""]
    print(f"converse: {r.status_code}, tools {[t['tool'] for t in tools]}")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
